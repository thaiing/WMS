const termsByLength = [...terms].sort(([left], [right]) => right.length - left.length);

export function isVietnameseLocale(): boolean {
  try {
    return (Local.get('themeConfig')?.globalI18n || 'vi') === 'vi';
  } catch {
    return true;
  }
}

export function translateViText(input: unknown): unknown {
  if (typeof input !== 'string' || !/[\u3400-\u9fff]/.test(input)) return input;

  const leading = input.match(/^\s*/)?.[0] || '';
  const trailing = input.match(/\s*$/)?.[0] || '';
  const source = input.trim();
  if (!source) return input;
  if (exact[source]) return `${leading}${exact[source]}${trailing}`;
  if (source.startsWith('易软通开源openWMS')) {
    return `${leading}${source.replace('易软通开源openWMS', 'DTI')}${trailing}`;
  }

  let match = source.match(/^请输入(.+?)[！!。]?$/);
  if (match) return `${leading}Vui lòng nhập ${lowerFirst(translateViText(match[1]) as string)}.${trailing}`;

  match = source.match(/^请选择(.+?)[！!。]?$/);
  if (match) return `${leading}Vui lòng chọn ${lowerFirst(translateViText(match[1]) as string)}.${trailing}`;

  match = source.match(/^(.+?)(必须填写|不能为空)[！!。]?$/);
  if (match) return `${leading}Vui lòng ${fieldAction(match[1])} ${lowerFirst(translateViText(match[1]) as string)}.${trailing}`;

  match = source.match(/^(.+?)名称$/);
  if (match) return `${leading}Tên ${lowerFirst(translateViText(match[1]) as string)}${trailing}`;

  match = source.match(/^(.+?)编号$/);
  if (match) return `${leading}Mã ${lowerFirst(translateViText(match[1]) as string)}${trailing}`;

  match = source.match(/^(.+?)单号$/);
  if (match) return `${leading}Số phiếu ${lowerFirst(translateViText(match[1]) as string)}${trailing}`;

  let result = source;
  for (const [zh, vi] of termsByLength) result = result.replaceAll(zh, ` ${vi} `);
  result = result
    .replace(/\s+([,.;:!?%）)])+/g, '$1')
    .replace(/([（(])\s+/g, '$1')
    .replace(/\s*([：])\s*/g, ': ')
    .replace(/\s{2,}/g, ' ')
    .trim();
  if (result && !/[\u3400-\u9fff]/.test(result)) {
    result = result.charAt(0).toLocaleUpperCase('vi-VN') + result.slice(1);
  }
  return `${leading}${result}${trailing}`;
}

const presentationKeys = new Set([
  'label',
  'title',
  'placeholder',
  'message',
  'tableTenantName',
  'dialogTitle',
  'buttonText',
  'text',
  'emptyText',
  'suffixText',
]);

export function translatePresentationData<T>(value: T, parentKey = ''): T {
  if (!isVietnameseLocale()) return value;
  if (Array.isArray(value)) {
    value.forEach((item) => translatePresentationData(item, parentKey));
  } else if (value && typeof value === 'object') {
    Object.entries(value as Record<string, unknown>).forEach(([key, item]) => {
      if (typeof item === 'string' && presentationKeys.has(key)) {
        (value as Record<string, unknown>)[key] = translateViText(item);
      } else {
        translatePresentationData(item, key);
      }
    });
  }
  return value;
}

function lowerFirst(value: string): string {
  return value ? value.charAt(0).toLocaleLowerCase('vi-VN') + value.slice(1) : value;
}

function fieldAction(field: string): 'nhập' | 'chọn' {
  return /(仓库|货主|客户|供应商|状态|类型|类别|日期|时间|部门|货位)/.test(field) ? 'chọn' : 'nhập';
}

const translationExcludedSelector = 'script, style, textarea, code, pre, [contenteditable="true"]';
const legacyBrandPattern = /(易软通|open\s*wms|easy\s*soft|esoftone|esoftong|yiruantong|yisoft)/i;
const legacyBrandReplacePattern = /(易软通开源openWMS|易软通|open\s*wms|easy\s*soft|esoftone|esoftong|yiruantong|yisoft)/gi;

function shouldNormalizeDisplayText(value: string): boolean {
  return /[\u3400-\u9fff]/.test(value) || legacyBrandPattern.test(value);
}

function translateDisplayText(value: string): string {
  return (translateViText(value) as string).replace(legacyBrandReplacePattern, 'DTI');
}

function isTranslationExcluded(node: Node): boolean {
  const element = node.nodeType === Node.ELEMENT_NODE ? (node as Element) : node.parentElement;
  return !!element?.closest(translationExcludedSelector);
}

function translateElement(element: Element): void {
  if (isTranslationExcluded(element)) return;

  for (const attribute of ['placeholder', 'title', 'aria-label']) {
    const value = element.getAttribute(attribute);
    if (value && shouldNormalizeDisplayText(value)) {
      const translated = translateDisplayText(value);
      if (translated !== value) element.setAttribute(attribute, translated);
    }
  }

  for (const child of Array.from(element.childNodes)) {
    if (child.nodeType === Node.TEXT_NODE && child.textContent && shouldNormalizeDisplayText(child.textContent)) {
      const translated = translateDisplayText(child.textContent);
      if (translated !== child.textContent) child.textContent = translated;
    } else if (child.nodeType === Node.ELEMENT_NODE) {
      translateElement(child as Element);
    }
  }
}

/**
 * Bao phủ phần chữ viết trực tiếp trong các file Vue và nội dung menu/trạng thái
 * trả động từ backend. Observer chỉ thay đổi text hiển thị, không thay đổi model.
 */
export function installVietnameseDisplayTranslator(root: Element): MutationObserver | undefined {
  if (!isVietnameseLocale()) return undefined;
  document.documentElement.lang = 'vi';
  document.title = translateDisplayText(document.title);
  translateElement(root);

  const observer = new MutationObserver((mutations) => {
    for (const mutation of mutations) {
      if (mutation.type === 'attributes' && mutation.target.nodeType === Node.ELEMENT_NODE) {
        translateElement(mutation.target as Element);
      }
      if (
        mutation.type === 'characterData' &&
        !isTranslationExcluded(mutation.target) &&
        mutation.target.textContent &&
        shouldNormalizeDisplayText(mutation.target.textContent)
      ) {
        const translated = translateDisplayText(mutation.target.textContent);
        if (translated !== mutation.target.textContent) mutation.target.textContent = translated;
      }
      for (const node of Array.from(mutation.addedNodes)) {
        if (node.nodeType === Node.ELEMENT_NODE) translateElement(node as Element);
        if (
          node.nodeType === Node.TEXT_NODE &&
          !isTranslationExcluded(node) &&
          node.textContent &&
          shouldNormalizeDisplayText(node.textContent)
        ) {
          const translated = translateDisplayText(node.textContent);
          if (translated !== node.textContent) node.textContent = translated;
        }
      }
    }
  });
  observer.observe(root, {
    childList: true,
    characterData: true,
    attributes: true,
    attributeFilter: ['placeholder', 'title', 'aria-label'],
    subtree: true,
  });
  return observer;
}
